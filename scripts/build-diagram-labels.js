#!/usr/bin/env node
/**
 * "Label the diagram" data from the textbook figures.
 *
 * Every image used by a question is read with macOS Vision OCR (scripts/ocr-labels.swift). The printed
 * labels (short text boxes) become drop zones: the app covers them and the student drags the words back.
 * Writes diagram-labels.js:
 *   const DIAGRAM_LABELS = { "<image path>": [{ t: "Nucleus", x, y, w, h }, …], … }   (box in % of the image)
 *
 * Hand review lives in scripts/diagram-label-fixes.json:
 *   { "<image path>": { "keep": true, "fix": { "OCR text": "right text" }, "drop": ["text", …] } }
 *   or { "keep": true, "labels": [{ t, x, y, w, h }, …] } to place labels by hand (box in %) when OCR is too poor.
 * Only images with "keep": true are shipped, so a new figure never goes live unreviewed.
 * `--all` writes every candidate (for reviewing in the app).
 *
 * Usage: node scripts/build-diagram-labels.js [--all]   (macOS only)
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const FIXES = path.join(__dirname, 'diagram-label-fixes.json');
const ALL = process.argv.includes('--all');

// Every image path referenced by a data module.
const images = new Set();
fs.readdirSync(ROOT).filter(f => f.endsWith('.js')).forEach(f => {
  const src = fs.readFileSync(path.join(ROOT, f), 'utf8');
  for (const m of src.matchAll(/image"?\s*:\s*["']((?:assets|images)\/[^"']+)/g)) images.add(m[1]);
});
const readable = [...images].filter(p => { try { return fs.statSync(path.join(ROOT, p)).size > 0; } catch (e) { return false; } }).sort();

const ocr = execFileSync('swift', [path.join(__dirname, 'ocr-labels.swift')], {
  cwd: ROOT, input: readable.join('\n') + '\n', maxBuffer: 64 << 20
}).toString().trim().split('\n').filter(Boolean).map(l => JSON.parse(l));

const clean = t => t.replace(/^[\s\-–—•·.>»:_~|]+|[\s\-–—•·.>»:_~|]+$/g, '').replace(/\s+/g, ' ');

/** Join a label printed over several lines: the next line starts just below the last one, left edges or centres aligned. */
function mergeLines(words) {
  const boxes = words.map(w => ({ ...w, lastY: w.y, lastH: w.h })).sort((a, b) => a.y - b.y);
  for (let i = 0; i < boxes.length; i++) {
    const a = boxes[i];
    for (let j = i + 1; j < boxes.length; j++) {
      const b = boxes[j];
      const gap = b.y - (a.lastY + a.lastH);
      const overlap = Math.min(a.x + a.w, b.x + b.w) - Math.max(a.x, b.x);
      const aligned = Math.abs(a.x - b.x) < 0.03 || overlap > 0.5 * Math.min(a.w, b.w);
      if (gap < -0.2 * a.lastH || gap > 0.6 * a.lastH || !aligned || Math.abs(a.lastH - b.h) > 0.5 * a.lastH) continue;
      a.t = /-$/.test(a.t) ? a.t.slice(0, -1) + b.t : a.t + ' ' + b.t;
      const x2 = Math.max(a.x + a.w, b.x + b.w);
      a.x = Math.min(a.x, b.x); a.w = x2 - a.x;
      a.h = b.y + b.h - a.y;
      a.lastY = b.y; a.lastH = b.h;
      boxes.splice(j, 1);
      j = i; // rescan for a further line below
    }
  }
  return boxes;
}

function labelsFor(row) {
  const words = row.words.filter(w => w.c > 0.4).map(w => ({ ...w, t: clean(w.t) })).filter(w => w.t);
  return mergeLines(words)
    .map(w => ({ ...w, t: clean(w.t) }))
    .filter(w => /[A-Za-z]{2}/.test(w.t) && w.t.length >= 3 && w.t.length <= 36 && w.t.split(' ').length <= 5);
}

// ALL CAPS labels read as shouting on screen; show them in sentence case.
const tidy = t => (t === t.toUpperCase() && /[A-Z]{3}/.test(t)) ? t[0] + t.slice(1).toLowerCase() : t;
const pct = v => Math.round(v * 1000) / 10;

const fixes = fs.existsSync(FIXES) ? JSON.parse(fs.readFileSync(FIXES, 'utf8')) : {};
const out = {};
ocr.forEach(row => {
  const fx = fixes[row.img] || {};
  if (!ALL && !fx.keep) return;
  if (fx.labels) { out[row.img] = fx.labels; return; } // hand-placed (boxes already in %), for figures OCR reads badly
  let labels = labelsFor(row).map(l => ({ ...l, t: tidy(l.t) }));
  labels = labels
    .filter(l => !(fx.drop || []).includes(l.t))
    .map(l => ({ ...l, t: (fx.fix || {})[l.t] || l.t }));
  if (labels.length < 3 || labels.length > 12) return;
  out[row.img] = labels.map(l => ({ t: l.t, x: pct(l.x), y: pct(l.y), w: pct(l.w), h: pct(l.h) }));
});

const header = '// Generated by scripts/build-diagram-labels.js from the textbook figures (macOS Vision OCR + hand review).\n' +
  '// image path -> printed labels with their box in % of the image. Do not edit by hand; edit scripts/diagram-label-fixes.json.\n';
fs.writeFileSync(path.join(ROOT, 'diagram-labels.js'),
  header + 'const DIAGRAM_LABELS = ' + JSON.stringify(out, null, 0).replace(/\],"/g, '],\n"') + ';\n');
console.log(`${readable.length}/${images.size} images readable, ${Object.keys(out).length} diagrams written${ALL ? ' (--all, unreviewed)' : ''}.`);
